let decoded: Uint8Array | null = null;

/** 1 for land, 0 for sea, row by row. */
export function worldMask(): Uint8Array {
  if (decoded) return decoded;
  const mask = new Uint8Array(WORLD_WIDTH * WORLD_HEIGHT);
  ROWS.forEach((row, y) => {
    let x = 0;
    row.split('.').forEach((run, i) => {
      const n = parseInt(run, 16);
      if (i % 2 === 1) mask.fill(1, y * WORLD_WIDTH + x, y * WORLD_WIDTH + x + n);
      x += n;
    });
  });
  decoded = mask;
  return mask;
}

/** Pixel position on the mask of a longitude and latitude. */
export function project(lon: number, lat: number): [number, number] {
  const miller = (1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * (lat * Math.PI) / 180)) * 180) / Math.PI;
  return [Math.round((lon - LON_WEST) * SCALE), Math.round((TOP - miller) * SCALE)];
}
